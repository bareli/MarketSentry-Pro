/** Resolve the best supported language for a given `hass` object. */
export function resolveLang(hass) {
  const raw = hass?.locale?.language || hass?.language || "en";
  if (STRINGS[raw]) return raw;
  const base = raw.split("-")[0];
  const match = SUPPORTED.find((lang) => lang.split("-")[0] === base);
  return match || "en";
}

/** Translate `key` for `lang`, substituting `{var}` placeholders from `vars`. */
export function t(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.en;
  let str = dict[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, v);
    }
  }
  return str;
}
